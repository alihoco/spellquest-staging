'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const base=__dirname+'/';
const source=require('./core/national-curriculum-catalogue.json');
const api=require('./adaptive-curriculum.js');
const profileApi=require('./learner-profiles.js');
const page=fs.readFileSync(base+'year6.html','utf8');
const server=fs.readFileSync(base+'server.js','utf8');
for(const code of page.split('<script>').slice(1).map(s=>s.split('</script>')[0]))new Function(code);
assert.equal(source.words.length,615);
assert.ok(page.includes('mixed-word-selection.js')&&page.includes('adaptive-curriculum.js'));
assert.ok(page.includes('ensureCurriculumLoaded()'));
assert.ok(page.includes('/core/national-curriculum-catalogue.json'));
assert.ok(page.includes('await ensureCurriculumLoaded()'), 'Do not begin playing before curriculum is loaded');
assert.ok(page.includes('catalogue-word-')&&page.includes('catalogue-next-'));
assert.ok(page.includes('Spelling can move')||page.includes('spelling can move'), 'Starting band cannot be fixed');
assert.ok(page.includes('new-school-year')&&page.includes('local-school-year'));
assert.ok(page.includes('changeSchoolYear(this.value)'));
assert.ok(page.includes('recordIndependent(spellStorage,profile'), 'Independent spelling needs ongoing band assessment');
assert.ok(page.includes('runKind===\x27new\x27'), 'Only genuine new word baseline attempts update placement');
assert.ok(page.includes('wordAudioClip(WORDS.find('), 'Bonus narration must use the full bank');
assert.ok(page.includes('wordAudioClip(w)'), 'Review narrator must use the full bank');
assert.ok(page.includes('replayCurrentWord()'),'Word replay must work with any loaded curriculum entry');
assert.ok(page.includes('spellmaster-catalogue-help-v1'), 'Unreviewed words need honest generic support');
assert.ok(!page.includes('const WORDS=['), 'The word bank must be replaceable at runtime');
const block=server.slice(server.indexOf('const CURRICULUM=require('),server.indexOf('const cache=new Map'));
assert.ok(block.includes("require('./core/national-curriculum-catalogue.json')"));
const clips={};
new Function('require','CLIPS',block)(name=>{
 assert.equal(name,'./core/national-curriculum-catalogue.json');return source;
},clips);
assert.equal(Object.keys(clips).filter(k=>k.startsWith('catalogue-word-')).length,615);
assert.equal(Object.keys(clips).filter(k=>k.startsWith('catalogue-next-')).length,615);
assert.ok(clips['catalogue-word-en-necessary-v1']==='necessary');
assert.ok(clips['catalogue-next-en-necessary-v1'].includes('necessary'));
assert.ok(clips['catalogue-word-en-they-re-v1']==="they're");
const localMap=new Map();
const storage={getItem:k=>localMap.has(k)?localMap.get(k):null,setItem:(k,v)=>localMap.set(k,String(v)),removeItem:k=>localMap.delete(k)};
const child=profileApi.add(storage,{alias:'Test Learner',birth:'2018-09',schoolYear:3});
assert.equal(child.schoolYear,3);
assert.equal(api.starter(child,8),'year2','School year and age cannot infer spelling attainment');
assert.equal(profileApi.updateSchoolYear(storage,child.id,6).schoolYear,6);
assert.equal(api.readPlacement(storage,profileApi.active(storage),8).currentBand,'year2');
storage.setItem(profileApi.historyKey(child),JSON.stringify({accident:{events:[{correct:true,afterHelp:false}],next:'2026-11-20'}}));
assert.equal(profileApi.summary(JSON.parse(storage.getItem(profileApi.historyKey(child))),'2026-11-18').wordsSeen,1,
 'Profile progress must include imported curriculum words');
api.savePlacement(storage,child,api.seedPreference(child,8));
assert.ok(storage.getItem(api.placementKey(child)));
profileApi.forget(storage,child.id);
assert.equal(storage.getItem(api.placementKey(child)),null,'Deleting tester profile removes its placement');
console.log('615-word audio allowlist, UI wiring, age-neutral ability placement, learner progress and local deletion validated');
