const assert=require('node:assert/strict');
const fs=require('node:fs');
const root=__dirname+'/';
const lesson=fs.readFileSync(root+'year6.html','utf8');
const styles=fs.readFileSync(root+'spellmaster-top-bars.css','utf8');
