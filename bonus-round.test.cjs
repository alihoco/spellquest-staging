'use strict';
const assert=require('node:assert/strict');
const bonus=require('./bonus-round.js');
const allEasy=Array.from({length:10},(_,i)=>({word:'word'+i,learned:true,initial:true,attempts:1}));
assert.equal(bonus.target(allEasy.slice(0,4)),5);
assert.equal(bonus.target(allEasy.slice(0,5)),10);
assert.equal(bonus.chooseRound(allEasy.slice(0,5)),null);
const ten=bonus.chooseRound(allEasy);assert.equal(ten.count,10);
const normal=[...allEasy.slice(0,4),{word:'word4',learned:true,initial:false,attempts:2}];
assert.equal(bonus.chooseRound(normal).count,5);
const hard=[{word:'a',learned:true,initial:false,attempts:2},{word:'b',learned:true,initial:false,attempts:3},{word:'c',learned:true,initial:true,attempts:1}];
assert.equal(bonus.chooseRound(hard).count,3);
assert.equal(bonus.chooseRound(hard,3),null);
const graded=bonus.grade(['necessary','foreign','rhythm'],['necessary','foreign','rhythm']);
assert.equal(graded.perfect,true);
assert.equal(graded.delayedMastery,false);
assert.equal(graded.coins,25);
assert.equal(graded.bonusPoints,100);
const partial=bonus.grade(['necessary','foreign','rhythm'],['necessary','foriegn','rhythm']);
assert.equal(partial.perfect,false);
assert.equal(partial.avatarItemChoiceEarned,false);
assert.equal(partial.coins,4);
assert.equal(partial.bonusPoints,20);
const values=new Map(),storage={getItem:k=>values.get(k)||null,setItem:(k,v)=>values.set(k,String(v))};
const learner={id:'lp-test123'};
const first=bonus.award(storage,learner,'round-unique-123',graded);
assert.equal(first.coins,25);
assert.equal(first.bonusPoints,100);
assert.deepEqual(first.hats,[]);
assert.deepEqual(first.inventory,[]);
assert.deepEqual(bonus.pendingRewards(storage,learner),['round-unique-123']);
assert.equal(bonus.availableChoices(storage,learner).length>=6,true);
const claimed=bonus.chooseAvatarReward(storage,learner,'round-unique-123','discovery-glasses');
assert.equal(claimed.selected,'discovery-glasses');
assert.deepEqual(claimed.inventory,['discovery-glasses']);
assert.deepEqual(bonus.pendingRewards(storage,learner),[]);
assert.equal(bonus.chooseAvatarReward(storage,learner,'round-unique-123','star-explorer-hat').alreadyClaimed,true);
assert.deepEqual(bonus.read(storage,learner).inventory,['discovery-glasses']);
assert.equal(bonus.availableChoices(storage,learner).some(x=>x.id==='discovery-glasses'),false);
assert.equal(bonus.award(storage,learner,'round-unique-123',graded).alreadyAwarded,true);
assert.equal(bonus.read(storage,learner).coins,25);
assert.equal(bonus.read(storage,learner).bonusPoints,100);
assert.equal(bonus.award(storage,{id:'lp-other123'},'round-unique-123',partial).coins,4);
assert.equal(bonus.read(storage,learner).rounds[0].notMastery,true);
assert.equal(bonus.read(storage,learner).rounds[0].avatarItemId,'discovery-glasses');
assert.throws(()=>bonus.chooseAvatarReward(storage,{id:'lp-other123'},'round-unique-123','comet-trainers'));
console.log('Bonus selection, independent recall, no-mastery rewards, learner isolation and idempotence validated');
