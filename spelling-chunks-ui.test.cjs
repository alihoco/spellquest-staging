'use strict';
const assert=require('node:assert/strict');
const p=require('./spelling-chunks-ui.js');
const backing=new Map(),store={getItem:k=>backing.get(k)||null,setItem:(k,v)=>backing.set(k,String(v))};
const a={id:'lp-a11a11'},b={id:'lp-b22b22'};
const word='necessary',teacher=[2,5,7];
assert.deepEqual(p.fromChunks(word,['ne','ces','sa','ry']),teacher);
assert.deepEqual(p.groups(word,[3,6]),['nec','ess','ary']);
assert.deepEqual(p.groups(word,[]),[word]);
assert.throws(()=>p.groups(word,[3,3]));
assert.throws(()=>p.groups(word,[0]));
assert.throws(()=>p.groups(word,[1,2,3,4,5]));
p.log(store,a,'offered',word,'s1');
p.log(store,a,'offered',word,'s1');
p.log(store,a,'opened',word,'s1');
let saved=p.choice(store,a,word,teacher,[3,6],'s1');
assert.equal(saved.custom,true);
assert.deepEqual(p.read(store,a).preferences[word].cuts,[3,6]);
assert.equal(p.read(store,b).preferences[word],undefined);
assert.equal(p.summary(p.read(store,a)).offered,1);
assert.equal(p.summary(p.read(store,a)).customSaves,1);
assert.equal(p.summary(p.read(store,a)).changedOpportunities,1);
p.log(store,a,'offered',word,'s2');
p.log(store,a,'custom_reused',word,'s2');
p.log(store,a,'custom_reused',word,'s2');
p.choice(store,a,word,teacher,[3,6],'s2');
assert.equal(p.summary(p.read(store,a)).customSaves,1,'Reconfirming custom grouping is not newly changing it');
assert.equal(p.summary(p.read(store,a)).reuses,1);
p.choice(store,a,word,teacher,teacher,'s3');
assert.equal(p.summary(p.read(store,a)).resets,1);
assert.equal(p.read(store,a).preferences[word].custom,false);
p.log(store,b,'offered',word,'t1');
p.choice(store,b,word,teacher,teacher,'t1');
assert.equal(p.summary(p.read(store,b)).customSaves,0);
assert.equal(p.summary(p.read(store,b)).keptDefault,1);
console.log('Splitter boundaries, profile isolation, changed-vs-kept and reuse event counting validated');
