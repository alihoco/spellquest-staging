'use strict';
const assert=require('node:assert/strict');
const V=require('./voice-tutor-policy.cjs');
let s=V.createVoiceState({approvedNarrator:'marin'});
assert.equal(s.state,'idle');
assert.throws(()=>V.advanceVoice(s,{type:'PLAY',approvedClip:'welcome'}));
s=V.advanceVoice(s,{type:'START',userGesture:true});
assert.equal(s.state,'teacher_speaking');
s=V.advanceVoice(s,{type:'TEACHER_DONE'});
s=V.advanceVoice(s,{type:'MIC_PERMISSION',allowed:true});
s=V.advanceVoice(s,{type:'LISTEN'});
s=V.advanceVoice(s,{type:'SPEECH_ACTIVITY_DETECTED',speechActivity:true});
assert.equal(s.spokenTurnDetected,true);
assert.equal(s.transcript,null);
assert.throws(()=>V.advanceVoice(s,{type:'WHOLE_WORD_RECOGNITION',confident:true,transcript:'necessary'}));
assert.throws(()=>V.advanceVoice(s,{type:'PHONEME_CORRECTION'}));
s=V.advanceVoice(s,{type:'PLAY',approvedClip:'word-necessary'});
assert.throws(()=>V.advanceVoice(s,{type:'LISTEN'}));
s=V.advanceVoice(s,{type:'AUDIO_ERROR'});
assert.equal(s.state,'audio_unavailable');
s=V.advanceVoice(s,{type:'TURN_OFF_AUDIO'});
assert.equal(s.state,'waiting_for_input');
console.log('Spellmaster voice teaching contract checks passed');
