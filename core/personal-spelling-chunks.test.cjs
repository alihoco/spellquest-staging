'use strict';
const assert=require('node:assert/strict');
const {validatePositions,groupsFromPositions,saveVisualPreference,loadVisualPreference}=require('./personal-spelling-chunks.cjs');
assert.deepEqual(groupsFromPositions('necessary',[2,5,7]),['ne','ces','sa','ry']);
assert.deepEqual(groupsFromPositions('government',[6]),['govern','ment']);
assert.deepEqual(groupsFromPositions('necessary',[]),['necessary']);
assert.equal(groupsFromPositions('necessary',[1,3,5,7]).join(''),'necessary');
assert.throws(()=>validatePositions('necessary',[0]));
assert.throws(()=>validatePositions('necessary',[1,1]));
assert.throws(()=>validatePositions('necessary',[6,2]));
assert.throws(()=>validatePositions('necessary',[1,2,3,4,5]));
const memory=new Map();
const save=(l,w,v)=>memory.set(l+':'+w,v),load=(l,w)=>memory.get(l+':'+w);
const entry=saveVisualPreference({learnerId:'lp-ab1234',wordId:'en-gb-y56-necessary',spelling:'necessary',positions:[2,5,7],save});
assert.equal(entry.speaksChunks,false);
assert.equal(entry.teachingClaims,false);
assert.equal(entry.independentMasteryEvidence,false);
assert.deepEqual(loadVisualPreference({learnerId:'lp-ab1234',wordId:'en-gb-y56-necessary',spelling:'necessary',load}).positions,[2,5,7]);
assert.equal(loadVisualPreference({learnerId:'lp-other',wordId:'en-gb-y56-necessary',spelling:'necessary',load}),null);
assert.equal(loadVisualPreference({learnerId:'lp-ab1234',wordId:'en-gb-y56-necessary',spelling:'necessaries',load}),null);
console.log('Personal spelling-chunk reconstruction, learner scoping and sound-teaching safeguards passed');
