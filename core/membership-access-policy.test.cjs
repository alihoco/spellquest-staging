'use strict';
const assert=require('node:assert/strict');
const a=require('./membership-access-policy.cjs');
assert.equal(a.plan('personal').amountGbp,10);
assert.equal(a.plan('school_30').amountGbp,50);
assert.equal(a.plan('school_unlimited').amountGbp,100);
assert.equal(a.plan('school_unlimited').pupilLimit,null);
for(const id of ['personal','school_30','school_unlimited'])
 assert.equal(a.plan(id).trialMonths,1,'All membership plans must offer 1 month free');
assert.equal(a.trialEndsAt('2026-11-18T10:30:00.000Z'),'2026-12-18T10:30:00.000Z');
assert.equal(a.trialEndsAt('2027-01-31T10:30:00.000Z'),'2027-02-28T10:30:00.000Z');
assert.equal(a.trialEndsAt('2028-01-31T10:30:00.000Z'),'2028-02-29T10:30:00.000Z');
assert.throws(()=>a.trialEndsAt('not-a-date'));
const trial={status:'trialing',validUntil:a.trialEndsAt('2026-11-18T10:30:00.000Z')};
assert.equal(a.canAddLearner({planId:'school_30',activeLearners:0,subscription:trial,asOf:'2026-11-20T10:00:00Z'}).allowed,true);
assert.equal(a.canAddLearner({planId:'school_30',activeLearners:0,subscription:trial,asOf:'2026-12-19T10:00:00Z'}).reason,'subscription_inactive');

const sub={status:'active',validUntil:'2027-11-18T00:00:00Z'},asOf='2026-11-18T21:00:00Z';
assert.equal(a.canAddLearner({planId:'personal',activeLearners:0,subscription:sub,asOf}).allowed,true);
assert.equal(a.canAddLearner({planId:'personal',activeLearners:1,subscription:sub,asOf}).reason,'seat_limit');
assert.equal(a.canAddLearner({planId:'school_30',activeLearners:29,subscription:sub,asOf}).allowed,true);
assert.equal(a.canAddLearner({planId:'school_30',activeLearners:30,subscription:sub,asOf}).reason,'seat_limit');
assert.equal(a.canAddLearner({planId:'school_unlimited',activeLearners:100000,subscription:sub,asOf}).allowed,true);
assert.equal(a.canAddLearner({planId:'school_unlimited',activeLearners:1,subscription:{status:'past_due'},asOf}).reason,'subscription_inactive');
const target={learnerId:'learner-a',schoolId:'school-a',classIds:['class-1'],guardianAccountIds:['parent-a']};
assert.equal(a.canViewLearner({actor:{role:'teacher',schoolId:'school-a'},target,assignedClassIds:['class-1']}),true);
assert.equal(a.canViewLearner({actor:{role:'teacher',schoolId:'school-a'},target,assignedClassIds:['class-2']}),false);
assert.equal(a.canViewLearner({actor:{role:'teacher',schoolId:'school-b'},target,assignedClassIds:['class-1']}),false);
assert.equal(a.canViewLearner({actor:{role:'school_admin',schoolId:'school-a'},target}),true);
assert.equal(a.canViewLearner({actor:{role:'school_admin',schoolId:'school-b'},target}),false);
assert.equal(a.canViewLearner({actor:{role:'guardian',accountId:'parent-a'},target}),true);
assert.equal(a.canViewLearner({actor:{role:'guardian',accountId:'parent-b'},target}),false);
assert.equal(a.canViewLearner({actor:{role:'individual',learnerId:'learner-a'},target}),true);
assert.equal(a.canManageSchool({actor:{role:'school_admin',schoolId:'school-b'},schoolId:'school-a'}),false);
console.log('Annual plan prices, pupil caps, subscription gates and cross-school/teacher permissions validated');
